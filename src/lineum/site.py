"""Write a Lineum site to disk: pages, assets, payload and discovery files."""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from datetime import datetime, timezone
from html import escape
from importlib import resources
from pathlib import Path
from typing import Any

from lineum import pages, payload
from lineum.markdown import plain
from lineum.model import Project
from lineum.pages import TYPE_LABELS, Site

MARKER = ".lineum-site"
# Hosting links that live in the output directory and must survive a rebuild.
KEEP = {".vercel", ".netlify", ".git", "CNAME"}


class SiteError(Exception):
    """The output directory cannot be written safely."""


@dataclass
class SiteOptions:
    title: str | None = None
    base_url: str | None = None
    noindex: bool = False
    include_sql: bool = True
    head_html: str = ""
    data: dict[str, Any] | None = None
    clean: bool = True
    queries: list[dict[str, str]] = field(default_factory=list)
    extra_files: dict[str, bytes] = field(default_factory=dict)


def prepare_output(out_dir: Path, clean: bool = True) -> None:
    """Create the output directory. Only ever deletes a directory Lineum created earlier."""
    if out_dir.exists():
        if not out_dir.is_dir():
            raise SiteError(f"{out_dir} exists and is not a directory.")
        contents = [p for p in out_dir.iterdir() if p.name != ".DS_Store" and p.name not in KEEP]
        if contents and not (out_dir / MARKER).exists():
            raise SiteError(
                f"{out_dir} is not empty and was not created by Lineum. Choose another --out directory "
                "or empty it first; Lineum will not delete files it did not write."
            )
        if clean and contents:
            for path in contents:
                if path.is_dir() and not path.is_symlink():
                    shutil.rmtree(path)
                else:
                    path.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / MARKER).write_text("This directory is generated by Lineum and is replaced on every build.\n")


def write(project: Project, summary: dict[str, Any], health: dict[str, Any], out_dir: Path,
          options: SiteOptions) -> dict[str, int]:
    title = options.title or _title(project.name)
    base_url = options.base_url.rstrip("/") + "/" if options.base_url else None
    site = Site(project, title=title, base_url=base_url, noindex=options.noindex, summary=summary,
                health=health, head_html=options.head_html)

    assets = out_dir / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    _copy_static(assets)

    data = payload.build(project, summary, health, title=title, base_url=base_url,
                         include_sql=options.include_sql, data=options.data, queries=options.queries)
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    text = text.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    (assets / "data.js").write_text(f"window.__LINEUM__={text};\n", encoding="utf-8")

    written = 0
    _write(out_dir / "index.html", pages.overview(site))
    for url in ("lineage.html", "health.html", "analyze.html"):
        _write(out_dir / url, pages.app_page(site, url))
    _write(out_dir / "404.html", pages.not_found(site))
    written += 5
    for node in project.nodes.values():
        _write(out_dir / node.url, pages.resource(site, node))
        written += 1

    _write(out_dir / "robots.txt", _robots(site))
    if base_url:
        _write(out_dir / "sitemap.xml", _sitemap(site))
    _write(out_dir / "llms.txt", _llms(site))
    _write(out_dir / "llms-full.txt", _llms_full(site))
    for name, content in options.extra_files.items():
        target = out_dir / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    return {"pages": written, "bytes": len(text)}


def _title(name: str) -> str:
    return name.replace("_", " ").replace("-", " ").title()


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _copy_static(target: Path) -> None:
    static = resources.files("lineum") / "static"
    for name in ("lineum.js", "lineum.css", "favicon.svg"):
        source = static / name
        if not source.is_file():
            if name == "favicon.svg":
                continue
            raise SiteError(
                f"The Lineum web app ({name}) is missing from the installed package. Reinstall Lineum, or "
                "build it from source with `npm --prefix web ci && npm --prefix web run build`."
            )
        (target / name).write_bytes(source.read_bytes())


def _robots(site: Site) -> str:
    if site.noindex:
        return "User-agent: *\nDisallow: /\n"
    lines = ["User-agent: *", "Allow: /"]
    if site.base_url:
        lines.append(f"Sitemap: {site.base_url}sitemap.xml")
    return "\n".join(lines) + "\n"


def _sitemap(site: Site) -> str:
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    urls = [""] + ["lineage.html", "health.html", "analyze.html"]
    urls += [node.url for node in site.project.nodes.values()]
    entries = "".join(
        f"<url><loc>{escape(site.base_url + url)}</loc><lastmod>{today}</lastmod></url>" for url in urls  # type: ignore[operator]
    )
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{entries}</urlset>\n')


def _href(site: Site, url: str) -> str:
    return f"{site.base_url}{url}" if site.base_url else url


def _llms(site: Site) -> str:
    """llms.txt: a Markdown index of the documentation for language models (llmstxt.org)."""
    project = site.project
    counts = site.summary.get("counts", {})
    lines = [
        f"# {site.title}",
        "",
        f"> dbt project documentation generated by Lineum: {counts.get('model', 0)} models, "
        f"{counts.get('source', 0)} sources and {counts.get('exposure', 0)} exposures, with model and column lineage.",
        "",
        f"The full text of every page, with columns and lineage, is in [llms-full.txt]({_href(site, 'llms-full.txt')}).",
        "",
    ]
    by_type: dict[str, list[Any]] = {}
    for node in project.nodes.values():
        by_type.setdefault(node.type, []).append(node)
    for node_type in ("model", "source", "seed", "snapshot", "exposure", "metric", "semantic_model",
                      "saved_query", "analysis", "function"):
        nodes = sorted(by_type.get(node_type, []), key=lambda n: n.display_name)
        if not nodes:
            continue
        lines.append(f"## {TYPE_LABELS.get(node_type, node_type)}s")
        lines.append("")
        for node in nodes:
            summary = plain(node.description, 160)
            lines.append(f"- [{node.display_name}]({_href(site, node.url)})" + (f": {summary}" if summary else ""))
        lines.append("")
    return "\n".join(lines)


def _llms_full(site: Site) -> str:
    project = site.project
    out = [f"# {site.title}", "", f"dbt project `{project.name}` documented by Lineum.", ""]
    for node in project.nodes.values():
        kind = TYPE_LABELS.get(node.type, node.type)
        out.append(f"## {node.display_name} ({kind.lower()})")
        out.append("")
        meta = [f"id: `{node.id}`"]
        if node.relation:
            meta.append(f"relation: `{node.relation}`")
        if node.materialized and node.type == "model":
            meta.append(f"materialized: {node.materialized}")
        if node.owner:
            meta.append(f"owner: {node.owner}")
        out.append(" · ".join(meta))
        out.append("")
        if node.description:
            out.append(node.description.strip())
            out.append("")
        if node.parents:
            out.append("Upstream: " + ", ".join(project.nodes[p].display_name for p in node.parents))
        if node.children:
            out.append("Downstream: " + ", ".join(project.nodes[c].display_name for c in node.children))
        if node.parents or node.children:
            out.append("")
        if node.columns:
            out.append("| Column | Type | Description |")
            out.append("| --- | --- | --- |")
            for column in node.columns:
                description = plain(column.description, 200).replace("|", "\\|")
                out.append(f"| {column.name} | {column.type or ''} | {description} |")
            out.append("")
    return "\n".join(out)
